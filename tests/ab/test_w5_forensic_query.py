def run(h: Harness) -> dict:
    part = synthetic.part_ids(5)
    synthetic.ensure_erp_part(h.erp_conn, part)
    synthetic.set_wms_inventory(h.wms_http.base_url, part, "WH-B", on_hand=60)
    synthetic.wait_both_converged(h.baseline_conn, h.ontology_hot_conn, part, "WH-B", 60, timeout_s=40.0)

    decision_ids = {}
    for name, client in h.clients.items():
        resp = client.propose("transfer_inventory", "user", "planner-1", {
            "source_warehouse": "WH-B", "destination_warehouse": "WH-A", "part": part.canonical_id, "quantity": 10,
        })
        decision_id = resp.json()["decision_id"]
        exec_resp = client.execute(decision_id)
        assert exec_resp.status_code == 202, exec_resp.text
        final = client.wait_terminal(decision_id, timeout_s=45.0)
        decision_ids[name] = decision_id
        assert final.get("status") == "OBSERVED_SUCCESS", final

    forensic = {
        "ontology": _forensic_ontology(h, decision_ids["ontology"]),
        "baseline": _forensic_baseline(h, decision_ids["baseline"]),
    }

    return {
        "workload": "W5_forensic_query",
        "decision_ids": decision_ids,
        "forensic": forensic,
        "part": part.canonical_id,
    }


def test_w5_forensic_query(harness: Harness):
    result = run(harness)
    for name, f in result["forensic"].items():
        assert f["complete"], (name, f)
